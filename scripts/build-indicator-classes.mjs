import { readFileSync, writeFileSync } from 'node:fs'
const target = 'supabase/migrations/20261118203649_indicator_asset_classes.sql'
const classes = JSON.parse(readFileSync('src/shared/indicators/classes.json', 'utf8'))
const previous = readFileSync('supabase/migrations/20261108011211_indicator_contract.sql', 'utf8').replaceAll('\r\n', '\n')
const rules = readFileSync('supabase/migrations/20261106232307_configured_alert_rules.sql', 'utf8').replaceAll('\r\n', '\n')
const validation = rules.slice(rules.indexOf('create function public.validate_configured_alert_rule()'), rules.indexOf('create trigger validate_configured_alert_rule'))
  .replace('create function', 'create or replace function')
  .replace("if not (asset_type in ('stock_br','stock_us','bdr') or\n      (asset_type in ('fii','reit') and new.metric in ('dy','pvp'))) then", 'if not public.supports_indicator_class(new.metric,asset_type) then')
const monitor = previous.slice(previous.indexOf('-- Debt/equity'))
  .replace('declare r record;', 'declare asset_class text; r record;')
  .replace("    if r.kind='indicator' then", "    if r.kind='indicator' then\n      select type::text into asset_class from public.assets where ticker=r.ticker;\n      if not found then continue; end if;")
  .replace("when 'net_margin' then f.net_margin end);", "when 'net_margin' then f.net_margin end,asset_class);")
const sql = `-- Generated by scripts/build-indicator-classes.mjs. Existing thresholds and history preserved.
create or replace function public.supports_indicator_class(p_metric text,p_asset_type text)
returns boolean language sql immutable security invoker set search_path='' as $classes$
 select coalesce((c->p_metric) ? p_asset_type,false)
 from (select '${JSON.stringify(classes)}'::jsonb as c) contract
$classes$;
revoke all on function public.supports_indicator_class(text,text) from public,anon;
grant execute on function public.supports_indicator_class(text,text) to authenticated,service_role;
create or replace function public.validated_indicator_value(p_metric text,p_source text,p_value numeric,p_asset_type text)
returns numeric language sql immutable security invoker set search_path='' as $classes$
 select case when public.supports_indicator_class(p_metric,p_asset_type)
 then public.validated_indicator_value(p_metric,p_source,p_value) else null end
$classes$;
revoke all on function public.validated_indicator_value(text,text,numeric,text) from public,anon;
grant execute on function public.validated_indicator_value(text,text,numeric,text) to authenticated,service_role;

${validation}
${monitor}`
if (process.argv.includes('--check')) {
  if (readFileSync(target, 'utf8').replaceAll('\r\n', '\n') !== sql) throw Error('Indicator asset classes SQL is out of date')
} else writeFileSync(target, sql)
