import { readFileSync, writeFileSync } from 'node:fs'
const target = 'supabase/migrations/20261108011211_indicator_contract.sql'
const contract = JSON.parse(readFileSync('src/shared/indicators/contract.json', 'utf8'))
const monitor = readFileSync('supabase/migrations/20261106233419_configured_alert_metric_units.sql', 'utf8')
  .replaceAll('\r\n', '\n')
  .replace("      if r.metric='debt_equity' and f.source<>'yahoo' then continue; end if;\n", '')
  .replace('observed := case r.metric', 'observed := public.validated_indicator_value(r.metric,f.source,case r.metric')
  .replace("when 'net_margin' then f.net_margin end;", "when 'net_margin' then f.net_margin end);")
const sql = `-- Generated by scripts/build-indicator-contract.mjs; raw thresholds are preserved.
CREATE OR REPLACE FUNCTION public.validated_indicator_value(p_metric text,p_source text,p_value numeric)
RETURNS numeric LANGUAGE sql IMMUTABLE SECURITY INVOKER SET search_path='' AS $contract$
 SELECT CASE WHEN NOT (c ? p_metric) OR p_source IN ('seed','synthetic')
   OR (c->p_metric->>'requiredSource' IS NOT NULL AND (c->p_metric->>'requiredSource') IS DISTINCT FROM p_source)
   OR p_value::text IN ('NaN','Infinity','-Infinity') THEN NULL ELSE p_value END
 FROM (SELECT '${JSON.stringify(contract)}'::jsonb AS c) AS contract
$contract$;
REVOKE ALL ON FUNCTION public.validated_indicator_value(text,text,numeric) FROM PUBLIC,anon;
GRANT EXECUTE ON FUNCTION public.validated_indicator_value(text,text,numeric) TO authenticated,service_role;

${monitor.replaceAll('\r\n', '\n')}`
if (process.argv.includes('--check')) {
  if (readFileSync(target, 'utf8').replaceAll('\r\n', '\n') !== sql) throw new Error('Indicator SQL contract is out of date')
} else writeFileSync(target, sql)
