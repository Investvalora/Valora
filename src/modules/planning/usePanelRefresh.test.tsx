import { act, renderHook } from '@testing-library/react'
import { afterEach, expect, it, vi } from 'vitest'
import { PANEL_REFRESH_MS, usePanelRefresh } from './usePanelRefresh'
afterEach(() => { vi.useRealTimers(); vi.restoreAllMocks() })
it('agenda consultas sem sobreposição, pausa offline e limpa o timer ao sair', async () => {
  vi.useFakeTimers(); vi.spyOn(document, 'visibilityState', 'get').mockReturnValue('visible')
  const online = vi.spyOn(navigator, 'onLine', 'get').mockReturnValue(true)
  let finish!: () => void
  const refresh = vi.fn(() => new Promise<void>(resolve => { finish = resolve }))
  const { result, unmount } = renderHook(() => usePanelRefresh(refresh, true))
  expect(result.current.nextCheck).toBe(Date.now() + PANEL_REFRESH_MS)
  await act(async () => { vi.advanceTimersByTime(PANEL_REFRESH_MS) })
  expect(refresh).toHaveBeenCalledTimes(1)
  await act(async () => { vi.advanceTimersByTime(PANEL_REFRESH_MS) })
  expect(refresh).toHaveBeenCalledTimes(1)
  await act(async () => { finish() })
  online.mockReturnValue(false)
  act(() => { window.dispatchEvent(new Event('offline')) })
  expect(result.current.paused).toBe(true)
  expect(result.current.nextCheck).toBeNull()
  online.mockReturnValue(true)
  act(() => { window.dispatchEvent(new Event('online')) })
  expect(refresh).toHaveBeenCalledTimes(2)
  unmount()
  await act(async () => { finish(); vi.advanceTimersByTime(PANEL_REFRESH_MS * 2) })
  expect(refresh).toHaveBeenCalledTimes(2)
})
it('não consulta sem carteira disponível e volta a conferir ao recuperar visibilidade', async () => {
  vi.useFakeTimers();vi.spyOn(navigator, 'onLine', 'get').mockReturnValue(true)
  const visibility = vi.spyOn(document, 'visibilityState', 'get').mockReturnValue('hidden')
  const refresh = vi.fn().mockResolvedValue(undefined)
  const { result, rerender } = renderHook(({ enabled }) => usePanelRefresh(refresh, enabled), { initialProps: { enabled: false } })
  await act(async () => { vi.advanceTimersByTime(PANEL_REFRESH_MS) })
  expect(refresh).not.toHaveBeenCalled()
  rerender({ enabled: true })
  expect(result.current.paused).toBe(true)
  visibility.mockReturnValue('visible')
  await act(async () => { document.dispatchEvent(new Event('visibilitychange')) })
  expect(refresh).toHaveBeenCalledOnce()
  expect(result.current.nextCheck).not.toBeNull()
})
