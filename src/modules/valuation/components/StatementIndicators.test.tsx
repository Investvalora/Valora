import { fireEvent, render, screen, within } from '@testing-library/react'
import { expect, it } from 'vitest'
import { StatementIndicators } from './StatementIndicators'

it('requires provenance and keeps missing values unavailable rather than zero', () => {
  render(<StatementIndicators />)
  fireEvent.click(screen.getByText('Indicadores por demonstrativo — pesquisa manual'))
  fireEvent.click(screen.getByRole('button', { name: 'Calcular indicadores do relatório' }))
  expect(screen.getByRole('alert')).toHaveTextContent('Informe a fonte HTTPS')
  fireEvent.change(screen.getByLabelText('Link HTTPS do relatório consultado'), { target: { value: 'https://example.com/annual-report' } })
  fireEvent.change(screen.getByLabelText(/Base contábil/), { target: { value: 'IFRS consolidado' } })
  fireEvent.change(screen.getByLabelText('Setor'), { target: { value: 'operating' } })
  fireEvent.change(screen.getByLabelText('Início do período'), { target: { value: '2025-01-01' } })
  fireEvent.change(screen.getByLabelText('Fim do período'), { target: { value: '2025-12-31' } })
  fireEvent.change(screen.getByLabelText('Dívida financeira total'), { target: { value: '100' } })
  fireEvent.change(screen.getByLabelText('Caixa e equivalentes'), { target: { value: '150' } })
  fireEvent.change(screen.getByLabelText('EBITDA do período'), { target: { value: '25' } })
  fireEvent.click(screen.getByRole('checkbox'))
  fireEvent.click(screen.getByRole('button', { name: 'Calcular indicadores do relatório' }))
  const result = screen.getByRole('region', { name: 'Resultados da pesquisa manual' })
  expect(within(result).getByText('-2')).toBeInTheDocument()
  expect(within(result).getAllByText('Indisponível')).toHaveLength(3)
  fireEvent.change(screen.getByLabelText('Dívida financeira total'), { target: { value: '200' } })
  expect(screen.queryByRole('region', { name: 'Resultados da pesquisa manual' })).not.toBeInTheDocument()
})

it('clears results and confirmation when switching statement groups', () => {
  render(<StatementIndicators />)
  fireEvent.click(screen.getByText('Indicadores por demonstrativo — pesquisa manual'))
  fireEvent.click(screen.getByRole('checkbox'))
  fireEvent.change(screen.getByLabelText('Grupo de indicadores'), { target: { value: 'fund' } })
  expect(screen.getByRole('checkbox')).not.toBeChecked()
  expect(screen.getByLabelText('Área vaga (m²)')).toBeInTheDocument()
  expect(screen.getByLabelText(/Todos os contratos/)).toBeInTheDocument()
})
it('calculates a complete annual series and rejects malformed rows', () => {
  render(<StatementIndicators />)
  fireEvent.click(screen.getByText('Indicadores por demonstrativo — pesquisa manual'))
  fireEvent.change(screen.getByLabelText('Grupo de indicadores'), { target: { value: 'growth' } })
  fireEvent.change(screen.getByLabelText('Link HTTPS do relatório consultado'), { target: { value: 'https://example.com/reports' } })
  fireEvent.change(screen.getByLabelText(/Base contábil/), { target: { value: 'IFRS consolidado' } })
  const series = Array.from({ length: 6 }, (_, i) => `${2020 + i}-01-01;${2020 + i}-12-31;${2020 + i};${100 * 1.1 ** i};${10 * 1.2 ** i}`).join('\n')
  fireEvent.change(screen.getByLabelText(/Seis exercícios/), { target: { value: series } })
  fireEvent.click(screen.getByRole('checkbox'))
  fireEvent.click(screen.getByRole('button', { name: 'Calcular indicadores do relatório' }))
  const result = screen.getByRole('region', { name: 'Resultados da pesquisa manual' })
  expect(within(result).getByText('10')).toBeInTheDocument()
  expect(within(result).getByText('20')).toBeInTheDocument()
  fireEvent.change(screen.getByLabelText(/Seis exercícios/), { target: { value: '2020;100' } })
  fireEvent.click(screen.getByRole('button', { name: 'Calcular indicadores do relatório' }))
  expect(screen.getByRole('alert')).toHaveTextContent('Confira as colunas')
})
