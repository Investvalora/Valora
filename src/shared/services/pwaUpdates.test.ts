import { afterEach, expect, it, vi } from 'vitest'
import { watchPwaUpdates } from './pwaUpdates'

afterEach(() => { vi.useRealTimers(); vi.restoreAllMocks() })

it('busca atualização ao abrir e retomar, limita chamadas e remove listeners', async () => {
  vi.useFakeTimers()
  const visible = vi.spyOn(document, 'visibilityState', 'get').mockReturnValue('visible')
  vi.spyOn(navigator, 'onLine', 'get').mockReturnValue(true)
  const update = vi.fn().mockResolvedValue(undefined)
  const stop = watchPwaUpdates({ update })
  await Promise.resolve()
  expect(update).toHaveBeenCalledTimes(1)
  document.dispatchEvent(new Event('visibilitychange'))
  expect(update).toHaveBeenCalledTimes(1)
  visible.mockReturnValue('hidden')
  await vi.advanceTimersByTimeAsync(30 * 60 * 1000)
  expect(update).toHaveBeenCalledTimes(1)
  visible.mockReturnValue('visible')
  document.dispatchEvent(new Event('visibilitychange'))
  await Promise.resolve()
  expect(update).toHaveBeenCalledTimes(2)
  stop()
  await vi.advanceTimersByTimeAsync(30 * 60 * 1000)
  window.dispatchEvent(new Event('online'))
  expect(update).toHaveBeenCalledTimes(2)
})

it('preserva o worker após falha e tenta quando a rede volta sem chamadas concorrentes', async () => {
  vi.useFakeTimers()
  vi.spyOn(document, 'visibilityState', 'get').mockReturnValue('visible')
  const online = vi.spyOn(navigator, 'onLine', 'get').mockReturnValue(false)
  const update = vi.fn().mockRejectedValue(new Error('offline'))
  const stop = watchPwaUpdates({ update })
  expect(update).not.toHaveBeenCalled()
  online.mockReturnValue(true)
  window.dispatchEvent(new Event('online'))
  window.dispatchEvent(new Event('online'))
  await Promise.resolve()
  expect(update).toHaveBeenCalledTimes(1)
  await vi.advanceTimersByTimeAsync(30 * 60 * 1000)
  expect(update).toHaveBeenCalledTimes(2)
  stop()
})
